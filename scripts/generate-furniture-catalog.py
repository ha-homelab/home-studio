#!/usr/bin/env python3
"""Generate the offline browser catalog from its canonical JSON source."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def generated_catalog():
    catalog = json.loads((ROOT / 'planner/catalog.json').read_text())
    assert catalog['version'] == 1
    categories = {entry['id'] for entry in catalog['categories']}
    styles = {entry['id']: entry for entry in catalog['styles']}
    ids = set()
    for model in catalog['models']:
        assert re.fullmatch(r'[a-z][a-z0-9_]{0,63}', model['id'])
        assert model['id'] not in ids
        ids.add(model['id'])
        assert model['category'] in categories and model['default_style'] in styles
        assert 1 <= len(model['parts']) <= 32
        for part in model['parts']:
            assert part['shape'] in ('box', 'cylinder')
            assert len(part['center']) == len(part['size']) == 3
            for axis, (center, size) in enumerate(zip(part['center'], part['size'])):
                assert size > 0
                low, high = (0, 1) if axis == 1 else (-.5, .5)
                assert center - size / 2 >= low - 1e-8
                assert center + size / 2 <= high + 1e-8
            for style in styles.values():
                color = style['materials'].get(part['material'], part['material'])
                assert re.fullmatch(r'#[0-9a-fA-F]{6}', color)
    return '// Generated by scripts/generate-furniture-catalog.py; edit catalog.json.\nexport const CATALOG = ' + json.dumps(catalog, ensure_ascii=False, separators=(',', ':')) + ';\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    destination = ROOT / 'planner/catalog.js'
    content = generated_catalog()
    if args.check:
        if not destination.exists() or destination.read_text() != content:
            raise SystemExit('Browser furniture catalog is stale; run scripts/generate-furniture-catalog.py')
        print('Furniture catalog is valid and browser copy is current.')
    else:
        destination.write_text(content)
